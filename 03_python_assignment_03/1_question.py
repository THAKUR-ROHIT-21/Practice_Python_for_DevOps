# 1. Write a Python program to print all odd and even numbers from 1 to 20.

# First Method

num1=int(input("Enter Your Number :- "))

for i in range(1,num1):
    if i%2==0:
        print("This is even number",i)
    else:
        print("This is odd number",i)

